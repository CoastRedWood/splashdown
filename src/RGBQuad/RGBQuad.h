// RGBQuad: an 8-bit RGBA colour (4 bytes).
#ifndef RGBQUAD_RGBQUAD_H
#define RGBQUAD_RGBQUAD_H

struct RGBQuad {
    unsigned char r;                    // +0x00
    unsigned char g;                    // +0x01
    unsigned char b;                    // +0x02
    unsigned char a;                    // +0x03
};

#endif
